def setrow_heights(w, cols):
    for r in rows:
        mx = 1
        for col in ['B','C']+cols:
            v = w[f'{col}{r}'].value
            if v:
                lines = sum(max(1, math.ceil(len(seg)/17)) for seg in str(v).split('\n'))
                mx = max(mx, lines)
        w.row_dimensions[r].height = max(37.5, mx*14+8)
    w.row_dimensions[23].height = 90

